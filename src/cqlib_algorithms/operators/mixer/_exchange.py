from __future__ import annotations

from collections.abc import Sequence

from cqlib.circuit import Circuit, Parameter
from cqlib.circuit.ansatz import EvolutionStrategy
from cqlib.circuit.gates import StandardGate
from cqlib.qis import Hamiltonian, Pauli, PauliString, TrotterMode

from ..ansatz import QAOAMixerEvolution


def add_exchange(
    hamiltonian: Hamiltonian,
    left: int,
    right: int,
    *,
    coefficient: float = 1.0,
) -> None:
    """Add ``coefficient * (XX + YY) / 2`` to a Hamiltonian."""
    for pauli in (Pauli.x(), Pauli.y()):
        term = PauliString(hamiltonian.num_qubits)
        term.set_pauli(left, pauli)
        term.set_pauli(right, pauli)
        hamiltonian.add_term(term, coefficient / 2.0)


def append_exchange(circuit: Circuit, left: int, right: int, beta: Parameter) -> None:
    """Append the exact unitary generated by ``(XX + YY) / 2``."""
    circuit.rxx(left, right, beta)
    circuit.ryy(left, right, beta)


def validate_exchange_evolution(evolution: QAOAMixerEvolution) -> None:
    """Reject Pauli-term randomization that can leave one-hot subspaces."""
    evolution.validate()
    mode = evolution.evolution_info().trotter_mode
    if mode is not None and mode not in {
        TrotterMode.first_order(),
        TrotterMode.second_order(),
    }:
        raise ValueError(
            "randomized evolution is not supported for one-hot exchange mixers"
        )


def append_exchange_product_formula(
    circuit: Circuit,
    pairs: Sequence[tuple[int, int]],
    beta: Parameter,
    evolution: QAOAMixerEvolution,
) -> None:
    """Compile a simultaneous exchange sum without breaking exchange blocks."""
    info = evolution.evolution_info()
    mode = info.trotter_mode
    if info.is_exact:
        for left, right in pairs:
            append_exchange(circuit, left, right, beta)
        return
    if mode == TrotterMode.first_order():
        angle = beta / float(info.steps)
        for _ in range(info.steps):
            for left, right in pairs:
                append_exchange(circuit, left, right, angle)
        return
    if mode == TrotterMode.second_order():
        angle = beta / float(2 * info.steps)
        for _ in range(info.steps):
            for left, right in pairs:
                append_exchange(circuit, left, right, angle)
            for left, right in reversed(tuple(pairs)):
                append_exchange(circuit, left, right, angle)
        return
    raise ValueError("unsupported evolution strategy for one-hot exchange mixer")


def append_controlled_exchange(
    circuit: Circuit,
    controls: Sequence[int],
    left: int,
    right: int,
    beta: Parameter,
    control_state: int,
) -> None:
    """Append an exact computational-state-controlled exchange."""
    controls_tuple = tuple(controls)
    for position, qubit in enumerate(controls_tuple):
        if not (control_state >> position) & 1:
            circuit.x(qubit)
    if controls_tuple:
        targets = [*controls_tuple, left, right]
        circuit.append_mc_gate(
            StandardGate.RXX(beta).control(len(controls_tuple)), targets
        )
        circuit.append_mc_gate(
            StandardGate.RYY(beta).control(len(controls_tuple)), targets
        )
    else:
        append_exchange(circuit, left, right, beta)
    for position, qubit in reversed(tuple(enumerate(controls_tuple))):
        if not (control_state >> position) & 1:
            circuit.x(qubit)


def transition_hamiltonian() -> Hamiltonian:
    """Return ``|0011><1100| + |1100><0011|`` on four local qubits."""
    hamiltonian = Hamiltonian(4)
    terms = (
        ((Pauli.x(), Pauli.x(), Pauli.x(), Pauli.x()), 1.0),
        ((Pauli.y(), Pauli.y(), Pauli.x(), Pauli.x()), -1.0),
        ((Pauli.y(), Pauli.x(), Pauli.y(), Pauli.x()), 1.0),
        ((Pauli.y(), Pauli.x(), Pauli.x(), Pauli.y()), 1.0),
        ((Pauli.x(), Pauli.y(), Pauli.y(), Pauli.x()), 1.0),
        ((Pauli.x(), Pauli.y(), Pauli.x(), Pauli.y()), 1.0),
        ((Pauli.x(), Pauli.x(), Pauli.y(), Pauli.y()), -1.0),
        ((Pauli.y(), Pauli.y(), Pauli.y(), Pauli.y()), 1.0),
    )
    for factors, sign in terms:
        term = PauliString(4)
        for qubit, pauli in enumerate(factors):
            term.set_pauli(qubit, pauli)
        hamiltonian.add_term(term, sign / 8.0)
    return hamiltonian


def transition_circuit(prefix: str) -> Circuit:
    """Build the exact one-parameter four-qubit transition circuit."""
    return QAOAMixerEvolution(
        4,
        mixer_operator=transition_hamiltonian(),
        strategy=EvolutionStrategy.exact(),
    ).build_circuit(prefix)


def complete_graph_edge_colors(
    num_vertices: int,
) -> tuple[tuple[tuple[int, int], ...], ...]:
    """Return a deterministic optimal round-robin edge coloring of ``K_n``."""
    vertices: list[int | None] = list(range(num_vertices))
    if num_vertices % 2:
        vertices.append(None)
    colors: list[tuple[tuple[int, int], ...]] = []
    for _ in range(len(vertices) - 1):
        pairs: list[tuple[int, int]] = []
        for offset in range(len(vertices) // 2):
            left = vertices[offset]
            right = vertices[-1 - offset]
            if left is not None and right is not None:
                pairs.append((min(left, right), max(left, right)))
        colors.append(tuple(sorted(pairs)))
        vertices = [vertices[0], vertices[-1], *vertices[1:-1]]
    return tuple(sorted(colors))


def ring_edge_layers(num_values: int) -> tuple[tuple[tuple[int, int], ...], ...]:
    """Return odd, even and optional closing-edge layers in circuit order."""
    first = tuple((start, start + 1) for start in range(0, num_values - 1, 2))
    second = tuple(
        (start, (start + 1) % num_values) for start in range(1, num_values, 2)
    )
    if num_values % 2:
        return first, second, ((num_values - 1, 0),)
    return first, second


def absolute_register_offsets(
    processing_times: tuple[int, ...], horizon: int
) -> tuple[int, ...]:
    """Return starting qubit offsets for absolute one-hot job registers."""
    offsets: list[int] = []
    cursor = 0
    for duration in processing_times:
        offsets.append(cursor)
        cursor += horizon - duration + 1
    return tuple(offsets)


def absolute_width(processing_times: tuple[int, ...], horizon: int) -> int:
    """Return the total number of absolute one-hot qubits."""
    return sum(horizon - duration + 1 for duration in processing_times)
